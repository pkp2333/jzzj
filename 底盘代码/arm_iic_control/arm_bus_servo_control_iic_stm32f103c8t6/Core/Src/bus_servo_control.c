typedef struct {
    QueueItem buffer[QUEUE_CAPACITY];
    uint8_t head;                   // ????????????¦Ë???
    uint8_t tail;                   // ??¦Â???????????¦Ë???
    uint8_t count;                  // ??????????????
} CircularQueue;

