static CircularQueue sendQueue_USART2;  // ????2???§µ????USART2?????
static CircularQueue sendQueue_USART3;  // ????3???§µ????USART3?????

// ???????????????????????????????????????
static CircularQueue* GetQueueByUart(UART_HandleTypeDef huart) {
    if (huart.Instance == USART2) return &sendQueue_USART2;  // ?????2???????????
    if (huart.Instance == USART3) return &sendQueue_USART3;  // ?????3???????????
    return NULL;  // ¦Ä???????
}

