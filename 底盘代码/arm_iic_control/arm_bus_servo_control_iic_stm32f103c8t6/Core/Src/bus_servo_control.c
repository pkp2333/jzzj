void bus_servo_Unloading(uint8_t id, uint8_t value, UART_HandleTypeDef huart) {
    uint8_t data[8] = {0};
    const uint8_t s_id = id & 0xff;
    const uint8_t len = 0x04;
    const uint8_t cmd = 0x03;
    const uint8_t addr = 0x28;
    const uint8_t checknum = (~(s_id + len + cmd + addr + value)) & 0xff;

    data[0] = 0xff; data[1] = 0xff; data[2] = s_id;
    data[3] = len; data[4] = cmd; data[5] = addr;
    data[6] = value; data[7] = checknum;

    uart_send_array(data, 8, huart);  // ?????????????§Ù???
}

