static uint8_t Queue_Enqueue(UART_HandleTypeDef huart, const uint8_t *data, uint16_t length) {
    CircularQueue *queue = GetQueueByUart(huart);
    if (!queue || length > MAX_PACKET_SIZE || queue->count >= QUEUE_CAPACITY) {
        return 1;   // ??????§¹/???????/????????
    }
    
    // ?????????????¦Â??
    memcpy(queue->buffer[queue->tail].data, data, length);
    queue->buffer[queue->tail].length = length;
    
    // ????¦Â??????¦Æ??§µ?
    queue->tail = (queue->tail + 1) % QUEUE_CAPACITY;
    queue->count++;
    return 0;
}

// ???????????????§Ö?????????????????
static void ProcessSendQueue(UART_HandleTypeDef huart) {
    CircularQueue *queue = GetQueueByUart(huart);
    if (!queue) return;  // ??§¹????
    
    while (queue->count > 0) {  // ?????§Ó????????????
        // ?????????
        QueueItem *current = &queue->buffer[queue->head];
        
        // ??????????????huart??????
        HAL_UART_Transmit(&huart, current->data, current->length, 0xFFFF);
//		 HAL_UART_Transmit_IT(&huart, current->data, current->length);
        
        // ?????????
        queue->head = (queue->head + 1) % QUEUE_CAPACITY;
        queue->count--;
    }
}

// ??????????????????+???????§µ?
static void uart_send_array(uint8_t *array, uint16_t length, UART_HandleTypeDef huart) {
    if (length == 0 || length > MAX_PACKET_SIZE) return;
    
    // ???????????????????????
    if (Queue_Enqueue(huart, array, length) == 0) {
        ProcessSendQueue(huart);  // ???????????????§µ??????????
    }
}

